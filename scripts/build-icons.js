'use strict';
/*
 * Builds web/assets/icons.svg — one SVG sprite — from icon libraries installed with npm:
 *   Lucide (lucide-static, ISC)       — all UI icons
 *   Simple Icons (simple-icons, CC0)  — the Claude mark on the Connectors page
 * Run: npm run build:icons   (re-run after adding an icon to ICONS below)
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const LUCIDE = path.join(ROOT, 'node_modules', 'lucide-static', 'icons');
const SIMPLE = path.join(ROOT, 'node_modules', 'simple-icons', 'icons');
const OUT = path.join(ROOT, 'web', 'assets', 'icons.svg');

// sprite id → Lucide icon name
const ICONS = {
  companion: 'message-circle-heart', memory: 'calendar-heart', connectors: 'plug-zap', send: 'arrow-up',
  prev: 'chevron-left', next: 'chevron-right', down: 'arrow-down', trash: 'trash-2', consent: 'shield-check',
  pause: 'pause', undo: 'undo-2', link: 'link', unlink: 'unlink', lock: 'lock', pulse: 'heart-pulse',
  face: 'smile', breathing: 'wind', hrv: 'activity', bot: 'bot', cpu: 'cpu', sparkles: 'sparkles',
  copy: 'copy', refresh: 'rotate-ccw', history: 'history', check: 'check', close: 'x', bell: 'bell-ring',
};
const BRANDS = { claude: 'claude' }; // sprite id → Simple Icons slug

const inner = (svg) => svg.replace(/<!--[\s\S]*?-->/g, '').replace(/<title>[\s\S]*?<\/title>/g, '')
  .replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '').trim();

const read = (dir, name) => {
  const f = path.join(dir, `${name}.svg`);
  if (!fs.existsSync(f)) throw new Error(`icon not found: ${f} (is the package installed?)`);
  return fs.readFileSync(f, 'utf8');
};

const symbols = [
  ...Object.entries(ICONS).map(([id, name]) =>
    `<symbol id="i-${id}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner(read(LUCIDE, name))}</symbol>`),
  ...Object.entries(BRANDS).map(([id, slug]) =>
    `<symbol id="i-${id}" viewBox="0 0 24 24" fill="currentColor" stroke="none">${inner(read(SIMPLE, slug))}</symbol>`),
];

const lucideVer = require(path.join(ROOT, 'node_modules', 'lucide-static', 'package.json')).version;
const simpleVer = require(path.join(ROOT, 'node_modules', 'simple-icons', 'package.json')).version;
fs.writeFileSync(OUT, `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Generated by scripts/build-icons.js from lucide-static@${lucideVer} (ISC) and simple-icons@${simpleVer} (CC0). Do not edit. -->\n${symbols.join('\n')}\n</svg>\n`);
console.log(`wrote ${path.relative(ROOT, OUT)} — ${symbols.length} icons`);
